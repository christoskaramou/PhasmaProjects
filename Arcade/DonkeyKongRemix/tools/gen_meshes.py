def heart_poly(n=32):
    pts = []
    for i in range(n):
        t = 2 * PI * i / n
        x = 16 * np.sin(t) ** 3; y = 13 * np.cos(t) - 5 * np.cos(2 * t) - 2 * np.cos(3 * t) - np.cos(4 * t)
        pts.append((x / 17, y / 17 + 0.1))
    return pts
