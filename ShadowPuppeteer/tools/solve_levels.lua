-- Finds a winning scripted input for every level under the real rules, and checks that doing nothing loses.
--   luajit tools/solve_levels.lua [tries] [level-id]      (from the game folder)
-- A solution = keyframes { t, lantern = { x, y }, <prop> = x (or z for the balloon) }; the input between keyframes
-- is linear (a drag), before the first it is the level's start, after the last it holds. Random search; the best
-- (won, then bonus star, then the quick mark, then earliest) is written to Assets/Scripts/puppet_solutions.lua.
local D = assert(loadfile("Assets/Scripts/sp_data.lua"))()
local R = assert(loadfile("Assets/Scripts/puppet_rules.lua"))()
local TRIES = tonumber(arg[1]) or 300
local ONLY = arg[2]

local function read_asset(p) local f = io.open("Assets/" .. p, "rb"); if not f then return nil end; local s = f:read("*a"); f:close(); return s end
local SCR = assert(loadfile("Assets/Scripts/puppet_scripts.lua"))()(D, read_asset)
local function script_fn(L, keys) return SCR.keyframes(L, keys) end
local function start_input(L) return SCR.start_input(L) end

local function simulate(L, f)
    local S = R.new_state(L)
    while not S.dead and not S.won do R.update(L, S, 1 / 60, f) end
    return S
end

local function rnd(a, b) return a + math.random() * (b - a) end
local function random_keys(L)
    local n = math.random(1, 3)
    local keys, t = {}, 0.5
    for _ = 1, n do
        t = t + rnd(0.2, 9.0)
        local k = { t = t, dur = rnd(0.4, 2.0), lantern = { rnd(D.LANTERN_X[1], D.LANTERN_X[2]), rnd(D.LANTERN_Y[1], D.LANTERN_Y[2]) } }
        for name, p in pairs(L.props) do
            if p.move == "x" and math.random() < 0.8 then k[name] = rnd(p.track[1], p.track[2])
            elseif p.move == "z" then k[name] = rnd(p.ztrack[1], p.ztrack[2]) end
        end
        keys[#keys + 1] = k
    end
    return keys
end

-- turns less than 0.6 s apart: the puppet trapped in a pocket, twitching (not a solution a player would see as one)
local function jitter(S)
    local n, last = 0, -9
    for _, e in ipairs(S.events) do
        if e.e == "turn" then
            if e.t - last < 0.6 then n = n + 1 end
            last = e.t
        end
    end
    return n
end
local function score(L, S)
    if not S.won then return -1 end
    local n = R.stars(L, S)
    return 1000 * n - S.t - 40 * jitter(S)
end

local function fmt(v)
    if type(v) == "table" then
        local parts = {}
        local keys = {}
        for k in pairs(v) do keys[#keys + 1] = k end
        table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
        for _, k in ipairs(keys) do
            local key = type(k) == "number" and "" or (k .. " = ")
            parts[#parts + 1] = key .. fmt(v[k])
        end
        return "{ " .. table.concat(parts, ", ") .. " }"
    elseif type(v) == "number" then
        return string.format("%.4f", v)
    end
    return tostring(v)
end

math.randomseed(tonumber(os.getenv('SP_SEED') or '7'))
local out = { "-- GENERATED by tools/solve_levels.lua: a scripted winning input per level (keyframed drags).",
    "-- rules_test.lua replays each and checks the win; the live scripted runs replay them too.", "return {" }
local report = {}
for _, lv in ipairs(D.LEVELS) do
    if not ONLY or lv.id == ONLY then
        local L = R.level(D, lv.id)
        local nothing = simulate(L, function() return start_input(L) end)
        local best, bs, bS = nil, -1e9, nil
        for i = 1, TRIES do
            local keys = random_keys(L)
            local S = simulate(L, script_fn(L, keys))
            local sc = score(L, S)
            if sc > bs then best, bs, bS = keys, sc, S end
            if sc >= 3000 - 25 and jitter(S) == 0 then break end
        end
        local stars = bS and select(1, R.stars(L, bS)) or 0
        report[#report + 1] = string.format("%s %-18s nothing: %s at %.2f s | best: %s %d stars at %.2f s, jitter %d", lv.id, lv.name,
            nothing.won and "WON (bad)" or tostring(nothing.dead), nothing.t, bS and bS.won and "won" or "NOT WON", stars,
            bS and bS.t or -1, bS and jitter(bS) or 0)
        print(report[#report])
        io.stdout:flush()
        if bS and bS.won then out[#out + 1] = string.format('  ["%s"] = %s,', lv.id, fmt(best)); print(out[#out]) end
    end
end
out[#out + 1] = "}"
if not ONLY then
    local f = io.open("Assets/Scripts/puppet_solutions.lua", "w")
    f:write(table.concat(out, "\n") .. "\n")
    f:close()
end
return { script_fn = script_fn }
